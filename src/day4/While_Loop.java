package day4;

public class While_Loop {
/*
 * for loop
 * for(initialization;condition;increment/decrement) - 1 to 10
 * while
 * initialization
 * while(condition){
 * statements...
 * increment/decrement
 * }
 * do while
 */
	public static void main(String[] args) {
		int i=1;
		while(i<=10) {//11<=10
			System.out.print(i + " ");//1 2.. 10 
			i++;
		}
	}

}
