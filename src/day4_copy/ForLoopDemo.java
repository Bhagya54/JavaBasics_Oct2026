package day4_copy;

public class ForLoopDemo {
/*
 * for(intialization;condition;increment/decrement){
 * 
 * }
 */
	public static void main(String[] args) {
		for(int i=1;i<=10;i++) {
			System.out.println("Hello");
		}
		
		//100 90 80 70...10
		for(int i=100;i>=10;i=i-10) {
			System.out.print(i + " ");
		}
		
		
	}

}
